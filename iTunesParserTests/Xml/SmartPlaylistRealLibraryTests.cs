using System.Xml.Linq;
using iTunesSmartParser.Data;
using iTunesSmartParser.Playlists;
using iTunesSmartParser.Xml;

namespace iTunesParserTests.Xml;

/// <summary>
/// Compares what is written to every smart playlist in a library that iTunes wrote. These can only be run locally, as
/// a library is private.
/// </summary>
[TestFixture]
[Explicit]
[Category("LocalOnly")]
public class SmartPlaylistRealLibraryTests
{
    private const string LIBRARY = "iTunesMusicLibrary.xml";

    private readonly PlaylistParser _parser = new();
    private XDocument _doc = null!;
    private List<(XElement Element, string Name, byte[] Info, byte[] Criteria, SmartPlaylistInformation Parsed)> _playlists = null!;

    [OneTimeSetUp]
    public async Task LoadLibrary()
    {
        _doc = await new ITunesXmlReader(LIBRARY).GetXDocument(CancellationToken.None);

        _playlists = PListParser.GetTopLevelDictionaryElement(_doc)!.PlistDictGet("Playlists")!.Elements()
            .Where(x => x.PlistDictGet("Smart Info") != null && x.PlistDictGet("Smart Criteria") != null)
            .Select(x => (x, (string) x.PlistDictGet("Name")!.Value, (byte[]) x.PlistDictGet("Smart Info")!.PlistParseValue(),
                (byte[]) x.PlistDictGet("Smart Criteria")!.PlistParseValue(), _parser.ParsePlaylistDetails(x).Filters!))
            .ToList();

        _playlists.Should().NotBeEmpty("the library has smart playlists in it");
    }

    [Test]
    public void Info_ReEncodedFromWhatIsParsed_IsExactlyWhatITunesWrote()
    {
        var wrong = _playlists.Where(x => !InfoWriter.Encode(x.Info, x.Parsed).SequenceEqual(x.Info)).Select(x => x.Name);

        wrong.Should().BeEmpty();
    }

    [Test]
    public void Info_GeneratedForANewPlaylist_IsWhatITunesWroteExceptForByteTwentyOne()
    {
        var differences = _playlists
            .SelectMany(x => Enumerable.Range(0, x.Info.Length)
                .Where(i => InfoWriter.Encode(x.Parsed)[i] != x.Info[i])
                .Select(i => (x.Name, Offset: i)))
            .ToList();

        differences.Should().OnlyContain(x => x.Offset == 21);
    }

    [Test]
    public void Criteria_GeneratedForANewPlaylist_IsWhatITunesWroteExceptForTheOrderOfRulesAndGroups()
    {
        var rulesUsed = _playlists.Where(x => x.Parsed.RuleConjunction != null).ToList();

        // Generated bytes must be as long as iTunes' and be read as the same rules...
        foreach (var playlist in rulesUsed)
        {
            var generated = CriteriaEncoder.Encode(playlist.Parsed.RuleConjunction!);

            generated.Length.Should().Be(playlist.Criteria.Length, playlist.Name);
            CriteriaParser.Parse(generated).Should().BeEquivalentTo(playlist.Parsed.RuleConjunction,
                options => options.IncludingAllRuntimeProperties(), playlist.Name);
        }

        // ... and for all but the ones with a rule and a group in the same list, they must be identical
        var different = rulesUsed
            .Where(x => !CriteriaEncoder.Encode(x.Parsed.RuleConjunction!).SequenceEqual(x.Criteria))
            .Where(x => !HasRuleAndGroupInOneList(x.Parsed.RuleConjunction!))
            .Select(x => x.Name);

        different.Should().BeEmpty();
    }

    [Test]
    public void Criteria_ReEncodedKeepingTheOrder_IsExactlyWhatITunesWrote()
    {
        var wrong = _playlists
            .Where(x => x.Parsed.RuleConjunction != null)
            .Where(x => !CriteriaEncoder.Encode(x.Parsed.RuleConjunction!, x.Criteria).SequenceEqual(x.Criteria))
            .Select(x => x.Name);

        wrong.Should().BeEmpty();
    }

    [Test]
    public async Task ApplyingThePlaylistsOwnValuesToEverySmartPlaylist_ChangesNothingInTheFile()
    {
        var directory = Directory.CreateTempSubdirectory().FullName;

        try
        {
            var path = Path.Combine(directory, "Library.xml");
            File.Copy(LIBRARY, path);
            var doc = await new ITunesXmlReader(path).GetXDocument(CancellationToken.None);
            var writer = new PlaylistWriter(_parser);

            foreach (var playlist in _playlists)
            {
                var id = int.Parse(playlist.Element.PlistDictGet("Playlist ID")!.Value);

                writer.ApplyPatch(doc, id, new PlaylistPatch
                {
                    Name = playlist.Name,
                    Limit = playlist.Parsed.Limit,
                    LiveUpdating = playlist.Parsed.LiveUpdating,
                    Rules = playlist.Parsed.RuleConjunction
                });
            }

            await new ITunesXmlWriter(path).SaveXDocument(doc, CancellationToken.None);

            File.ReadAllBytes(path).Should().Equal(File.ReadAllBytes(LIBRARY));
        }
        finally
        {
            Directory.Delete(directory, true);
        }
    }

    private static bool HasRuleAndGroupInOneList(Conjunction conjunction) =>
        conjunction is {Rules.Count: > 0, SubConjunctions.Count: > 0} ||
        conjunction.SubConjunctions.Any(HasRuleAndGroupInOneList);
}
